// Writes the renderer's icon components as gpui-client/assets/icons/<group>/<name>.svg from the
// icons-dump page's output (icons-dump-<theme>.json): one monochrome SVG per glyph, its stroke
// width on the root <svg> so decibell_ui::Icon::stroke_width can redraw it, the size attributes
// set to the viewBox. Usage: node icons/extract.mjs <icons-dump-nocturne.json>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ASSETS = path.resolve(here, '../../../assets/icons');
const { entries } = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));

let written = 0;
const groups = new Map();
for (const { group, name, svg, source } of entries) {
  let out = svg
    .replace(/<svg([^>]*)>/, (_, attrs) => {
      const box = attrs.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
      const [, , w, h] = box.split(/\s+/);
      const kept = attrs
        .replace(/\s(width|height|class|aria-hidden|style)="[^"]*"/g, '')
        .replace(/\sxmlns="[^"]*"/, '');
      return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}"${kept}>`;
    })
    .replace(/\sclass="[^"]*"/g, '');
  out = `<!-- electron-client/src/${source} (generated by tools/electron-captures/icons/extract.mjs) -->\n${out}\n`;
  const file = path.join(ASSETS, group, `${name}.svg`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old !== out) {
    fs.writeFileSync(file, out);
    written++;
  }
  groups.set(group, (groups.get(group) ?? 0) + 1);
}
console.log(`${entries.length} icons (${[...groups].map(([g, n]) => `${g} ${n}`).join(', ')}), ${written} written`);
