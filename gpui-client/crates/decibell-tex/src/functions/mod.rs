/// `functions[name]`, with the interned name.
pub fn lookup(name: &str) -> Option<(&'static str, &'static FunctionSpec)> {
    let t = table::TABLE;
    let i = t
        .binary_search_by(|e| e.0.as_bytes().cmp(name.as_bytes()))
        .ok()?;
    let (n, m, k) = t[i];
    Some((n, &ALL[m as usize][k as usize]))
}

/// `functions[name]`.
pub fn get(name: &str) -> Option<&'static FunctionSpec> {
    lookup(name).map(|e| e.1)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Rebuilds the sorted name table from `ALL` and compares it with `table.rs`; with
    /// `UPDATE_TABLES=1` it rewrites the file.
    #[test]
    fn table_is_current() {
        let mut entries: Vec<(&str, usize, usize)> = Vec::new();
        for (m, specs) in ALL.iter().enumerate() {
            for (k, spec) in specs.iter().enumerate() {
                for n in spec.names {
                    entries.retain(|e| e.0 != *n); // later definitions win, as in KaTeX
                    entries.push((n, m, k));
                }
            }
        }
        entries.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
        let mut out = String::from(
            "// Generated by `functions::tests::table_is_current`. Do not edit.\n\n#[rustfmt::skip]\npub static TABLE: &[(&str, u8, u8)] = &[\n",
        );
        for (n, m, k) in &entries {
            out.push_str(&format!("    ({:?}, {}, {}),\n", n, m, k));
        }
        out.push_str("];\n");
        // `file!()` is absolute, relative to the manifest dir, or relative to the workspace root.
        let here = std::path::Path::new(file!());
        let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let candidates = [
            here.with_file_name("table.rs"),
            manifest.join(here).with_file_name("table.rs"),
            manifest.join("src/functions/table.rs"),
        ];
        let path = candidates
            .iter()
            .find(|p| p.exists())
            .cloned()
            .unwrap_or_else(|| candidates[2].clone());
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != out {
            if std::env::var("UPDATE_TABLES").is_ok() {
                std::fs::write(&path, out).unwrap();
            } else {
                panic!("functions/table.rs is stale: rerun with UPDATE_TABLES=1");
            }
        }
    }
}
