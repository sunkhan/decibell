#!/usr/bin/env node
// Generates decibell-tex's static tables from KaTeX's own (evaluated) sources:
//
//   src/data/symbols_data.rs       symbols.ts            symbols[mode] (incl. loop-defined entries)
//   src/data/font_metrics_data.rs  fontMetricsData.js    per-font [depth,height,italic,skew,width] ×1e5
//   src/data/macros_data.rs        macros.ts (+ the defineMacro calls in functions/, environments/)
//   src/data/unicode_data.rs       unicodeSymbols.js (evaluated: needs String.normalize),
//                                  unicodeSupOrSub.ts, unicodeAccents.js
//   src/svg_geometry.rs            the static `path` record, between the GENERATED PATHS markers
//                                  (the functions above the markers are a hand port)
//
// KaTeX's TypeScript is bundled with the esbuild that electron-client already has, into a
// temporary CommonJS module, and evaluated, so loop-defined symbols and computed tables come out
// exactly as KaTeX builds them.
//
// Usage (from anywhere):  node gpui-client/crates/decibell-tex/tools/gen_tables.mjs [katexDir]
// Default katexDir: <repo>/electron-client/node_modules/katex (must be 0.18.4).
// The font tables (src/data/font_advances.rs) come from tools/gen_font_tables.py.

import {createRequire} from "node:module";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {fileURLToPath} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const crate = path.resolve(here, "..");
const repo = path.resolve(crate, "../../..");
const katexDir = path.resolve(process.argv[2] ?? path.join(repo, "electron-client/node_modules/katex"));
const KATEX_VERSION = "0.18.4";

const pkg = JSON.parse(fs.readFileSync(path.join(katexDir, "package.json"), "utf8"));
if (pkg.version !== KATEX_VERSION) {
    console.error(`expected KaTeX ${KATEX_VERSION} at ${katexDir}, found ${pkg.version}`);
    process.exit(1);
}

// ---------------------------------------------------------------------------------------------
// Bundle KaTeX's internals.
const requireFromClient = createRequire(path.join(repo, "electron-client/package.json"));
const esbuild = requireFromClient("esbuild");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "decibell-tex-gen-"));
const src = path.join(katexDir, "src");
const entry = path.join(tmp, "entry.ts");
fs.writeFileSync(entry, `
import symbols from ${JSON.stringify(path.join(src, "symbols"))};
import metricMap from ${JSON.stringify(path.join(src, "fontMetricsData"))};
import {_macros} from ${JSON.stringify(path.join(src, "defineMacro"))};
import ${JSON.stringify(path.join(src, "macros"))};
import ${JSON.stringify(path.join(src, "functions"))};
import ${JSON.stringify(path.join(src, "environments"))};
import unicodeAccents from ${JSON.stringify(path.join(src, "unicodeAccents"))};
import unicodeSymbols from ${JSON.stringify(path.join(src, "unicodeSymbols"))};
import {uSubsAndSups, unicodeSubRegEx} from ${JSON.stringify(path.join(src, "unicodeSupOrSub"))};
import {path as svgPath, sqrtPath, innerPath, tallDelim, phasePath} from ${JSON.stringify(path.join(src, "svgGeometry"))};
export {symbols, metricMap, _macros, unicodeAccents, unicodeSymbols, uSubsAndSups, unicodeSubRegEx, svgPath, sqrtPath, innerPath, tallDelim, phasePath};
`);
const bundle = path.join(tmp, "katex_internals.cjs");
esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    platform: "node",
    format: "cjs",
    outfile: bundle,
    logLevel: "warning",
});
const K = createRequire(import.meta.url)(bundle);
fs.rmSync(tmp, {recursive: true, force: true});

// ---------------------------------------------------------------------------------------------
// Helpers.

/** A Rust string literal for `s` (printable ASCII kept, everything else escaped). */
function rs(s) {
    let out = '"';
    for (const ch of s) {
        const cp = ch.codePointAt(0);
        if (cp >= 0xd800 && cp <= 0xdfff) {
            throw new Error(`lone surrogate in ${JSON.stringify(s)}`);
        }
        if (ch === "\\") out += "\\\\";
        else if (ch === '"') out += '\\"';
        else if (ch === "\n") out += "\\n";
        else if (ch === "\r") out += "\\r";
        else if (ch === "\t") out += "\\t";
        else if (cp >= 0x20 && cp < 0x7f) out += ch;
        else out += "\\u{" + cp.toString(16) + "}";
    }
    return out + '"';
}

/** A Rust char literal. */
function rc(ch) {
    if ([...ch].length !== 1) throw new Error(`not one code point: ${JSON.stringify(ch)}`);
    const cp = ch.codePointAt(0);
    if (ch === "\\") return "'\\\\'";
    if (ch === "'") return "'\\''";
    if (cp >= 0x20 && cp < 0x7f) return `'${ch}'`;
    return `'\\u{${cp.toString(16)}}'`;
}

const byUtf8 = (a, b) => Buffer.compare(Buffer.from(a, "utf8"), Buffer.from(b, "utf8"));

function header(what) {
    return `// Generated by tools/gen_tables.mjs from KaTeX ${KATEX_VERSION} ${what}. Do not edit; regenerate.\n`;
}

function write(rel, text) {
    const file = path.join(crate, rel);
    fs.writeFileSync(file, text);
    console.log(`wrote ${rel} (${text.length} bytes)`);
}

// ---------------------------------------------------------------------------------------------
// symbols_data.rs

const GROUP = {
    "bin": "Bin", "close": "Close", "inner": "Inner", "open": "Open", "punct": "Punct",
    "rel": "Rel", "accent-token": "AccentToken", "mathord": "MathOrd", "op-token": "OpToken",
    "spacing": "Spacing", "textord": "TextOrd",
};
const FONT = {"main": "M", "ams": "A"};

function symbolTable(mode) {
    const t = K.symbols[mode];
    const names = Object.keys(t).sort(byUtf8);
    const lines = names.map((name) => {
        const {font, group, replace} = t[name];
        const keys = Object.keys(t[name]).join(",");
        if (keys !== "font,group,replace") throw new Error(`unexpected symbol shape ${name}: ${keys}`);
        if (!(font in FONT)) throw new Error(`unknown font ${font}`);
        if (!(group in GROUP)) throw new Error(`unknown group ${group}`);
        if (replace != null && typeof replace !== "string") throw new Error(`bad replace ${name}`);
        const rep = replace ? `Some(${rs(replace)})` : "None";
        return `    (${rs(name)}, c(${FONT[font]}, ${GROUP[group]}, ${rep})),`;
    });
    return {count: names.length, text: lines.join("\n")};
}

{
    const math = symbolTable("math");
    const text = symbolTable("text");
    write("src/data/symbols_data.rs", header("src/symbols.ts") + `//! \`symbols.math\` / \`symbols.text\`, sorted by UTF-8 bytes for binary search.
//! ${math.count} math-mode and ${text.count} text-mode entries.

use crate::symbols::CharInfo;
use crate::symbols::Group::*;
use crate::symbols::SymbolFont::{Ams as A, Main as M};

const fn c(
    font: crate::symbols::SymbolFont,
    group: crate::symbols::Group,
    replace: Option<&'static str>,
) -> CharInfo {
    CharInfo {
        font,
        group,
        replace,
    }
}

#[rustfmt::skip]
pub static MATH: &[(&str, CharInfo)] = &[
${math.text}
];

#[rustfmt::skip]
pub static TEXT: &[(&str, CharInfo)] = &[
${text.text}
];
`);
}

// ---------------------------------------------------------------------------------------------
// font_metrics_data.rs

const FONT_NAME = {
    "AMS-Regular": "AmsRegular", "Caligraphic-Regular": "CaligraphicRegular",
    "Fraktur-Regular": "FrakturRegular", "Main-Bold": "MainBold",
    "Main-BoldItalic": "MainBoldItalic", "Main-Italic": "MainItalic",
    "Main-Regular": "MainRegular", "Math-BoldItalic": "MathBoldItalic",
    "Math-Italic": "MathItalic", "SansSerif-Bold": "SansSerifBold",
    "SansSerif-Italic": "SansSerifItalic", "SansSerif-Regular": "SansSerifRegular",
    "Script-Regular": "ScriptRegular", "Size1-Regular": "Size1Regular",
    "Size2-Regular": "Size2Regular", "Size3-Regular": "Size3Regular",
    "Size4-Regular": "Size4Regular", "Typewriter-Regular": "TypewriterRegular",
};

{
    let out = header("src/fontMetricsData.js") + `//! Character metrics per font: \`(UTF-16 code unit, [depth, height, italic, skew, width] × 100000)\`,
//! sorted by code unit. Every KaTeX value has at most five decimals, so \`n as f64 / 100000.0\`
//! (a correctly rounded division) is the same double as KaTeX's literal.

use crate::fonts::FontName;

pub type Metrics = [i32; 5];

pub fn table(font: FontName) -> &'static [(u16, Metrics)] {
    match font {
`;
    const fonts = Object.keys(K.metricMap);
    for (const f of fonts) {
        if (!(f in FONT_NAME)) throw new Error(`unknown metric font ${f}`);
        out += `        FontName::${FONT_NAME[f]} => ${constName(f)},\n`;
    }
    out += "    }\n}\n";
    let total = 0;
    for (const f of fonts) {
        const t = K.metricMap[f];
        const codes = Object.keys(t).map(Number).sort((a, b) => a - b);
        out += `\n#[rustfmt::skip]\nstatic ${constName(f)}: &[(u16, Metrics)] = &[\n`;
        for (const code of codes) {
            if (code > 0xffff) throw new Error(`code ${code} > u16`);
            const v = t[code];
            if (v.length !== 5) throw new Error(`metrics length ${f} ${code}`);
            const ns = v.map((x) => {
                const n = Math.round(x * 1e5);
                if (n / 1e5 !== x) throw new Error(`${f} ${code}: ${x} not representable ×1e5`);
                return n;
            });
            out += `    (${code}, [${ns.join(", ")}]),\n`;
            total++;
        }
        out += "];\n";
    }
    write("src/data/font_metrics_data.rs", out);
    console.log(`  ${total} metric entries`);
}

function constName(fontName) {
    return fontName.toUpperCase().replace(/-/g, "_");
}

// ---------------------------------------------------------------------------------------------
// macros_data.rs

{
    const names = Object.keys(K._macros).sort(byUtf8);
    const fnNames = [];
    const lines = names.map((name) => {
        const v = K._macros[name];
        if (typeof v === "string") {
            return `    (${rs(name)}, M::Str(${rs(v)})),`;
        } else if (typeof v === "function") {
            fnNames.push(name);
            return `    (${rs(name)}, M::Fn),`;
        } else {
            throw new Error(`macro ${name} is neither string nor function: ${JSON.stringify(v)}`);
        }
    });
    write("src/data/macros_data.rs", header("src/macros.ts (+ defineMacro calls in functions/ and environments/)") +
`//! The built-in macro table, sorted by UTF-8 bytes. \`Str\` bodies are verbatim; \`Fn\` entries are
//! function-valued macros, implemented in Rust by name (${fnNames.length} of them:
//! ${fnNames.join(" ")}).

use crate::macros::BuiltinMacro as M;

#[rustfmt::skip]
pub static BUILTIN: &[(&str, M)] = &[
${lines.join("\n")}
];
`);
    console.log(`  ${names.length} macros, function-valued: ${fnNames.join(" ")}`);
}

// ---------------------------------------------------------------------------------------------
// unicode_data.rs

{
    const us = K.unicodeSymbols;
    const usKeys = Object.keys(us).sort(byUtf8);
    const sub = K.uSubsAndSups;
    const subKeys = Object.keys(sub).sort(byUtf8);
    const src = K.unicodeSubRegEx.source;
    const m = /^\^\[([^\]]*)\]$/u.exec(src);
    if (!m) throw new Error(`unexpected unicodeSubRegEx ${src}`);
    const subChars = [...m[1]].sort(byUtf8);
    const acc = K.unicodeAccents;
    const accKeys = Object.getOwnPropertyNames(acc).sort(byUtf8);
    for (const k of accKeys) {
        const keys = Object.keys(acc[k]).sort().join(",");
        if (keys !== "math,text" && keys !== "text") throw new Error(`accent shape ${k}: ${keys}`);
    }
    write("src/data/unicode_data.rs", header("src/unicodeSymbols.js (evaluated), src/unicodeSupOrSub.ts, src/unicodeAccents.js") +
`//! Unicode lookup tables, each sorted by key.

/// \`unicodeSymbols\`: a precomposed letter → the letter followed by its combining accents.
#[rustfmt::skip]
pub static UNICODE_SYMBOLS: &[(char, &str)] = &[
${usKeys.map((k) => `    (${rc(k)}, ${rs(us[k])}),`).join("\n")}
];

/// \`uSubsAndSups\`: a Unicode sub/superscript character → the plain character.
#[rustfmt::skip]
pub static SUBS_AND_SUPS: &[(char, &str)] = &[
${subKeys.map((k) => `    (${rc(k)}, ${rs(sub[k])}),`).join("\n")}
];

/// The character class of \`unicodeSubRegEx\` (\`/^[…]/\`): the subscript characters.
#[rustfmt::skip]
pub static SUB_CHARS: &[char] = &[
${subChars.map((c) => `    ${rc(c)},`).join("\n")}
];

/// \`unicodeAccents\`: combining accent → (text-mode command, math-mode command).
#[rustfmt::skip]
pub static UNICODE_ACCENTS: &[(char, &str, Option<&str>)] = &[
${accKeys.map((k) => `    (${rc(k)}, ${rs(acc[k].text)}, ${acc[k].math ? `Some(${rs(acc[k].math)})` : "None"}),`).join("\n")}
];
`);
    console.log(`  ${usKeys.length} unicodeSymbols, ${subKeys.length} sub/sups, ${accKeys.length} accents`);
}

// ---------------------------------------------------------------------------------------------
// svg_geometry.rs: the static path record, spliced between the markers.

{
    const file = path.join(crate, "src/svg_geometry.rs");
    const BEGIN = "// BEGIN GENERATED PATHS (tools/gen_tables.mjs)";
    const END = "// END GENERATED PATHS";
    const old = fs.readFileSync(file, "utf8");
    const a = old.indexOf(BEGIN);
    const b = old.indexOf(END);
    if (a < 0 || b < a) throw new Error("svg_geometry.rs: generated-path markers not found");
    const names = Object.keys(K.svgPath).sort(byUtf8);
    const body = `${BEGIN}
/// The static \`path\` record of svgGeometry.ts (${names.length} entries), sorted by name.
#[rustfmt::skip]
static PATHS: &[(&str, &str)] = &[
${names.map((n) => `    (${rs(n)}, ${rs(K.svgPath[n])}),`).join("\n")}
];
`;
    let text = old.slice(0, a) + body + old.slice(b);

    // Test vectors for the hand-ported parametric paths: FNV-1a 64 of KaTeX's own output.
    const fnv = (s) => {
        let h = 0xcbf29ce484222325n;
        for (const byte of Buffer.from(s, "utf8")) {
            h ^= BigInt(byte);
            h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
        }
        return "0x" + h.toString(16).padStart(16, "0");
    };
    const num = (x) => (Object.is(x, -0) ? "-0.0" : Number.isInteger(x) ? `${x}.0` : `${x}`);
    const cases = [];
    for (const size of ["sqrtMain", "sqrtSize1", "sqrtSize2", "sqrtSize3", "sqrtSize4", "sqrtTall", "bogus"]) {
        for (const ev of [0, 0.01, 0.0333]) {
            for (const vbh of [1080, 3000.5]) {
                const s = K.sqrtPath(size, ev, vbh);
                cases.push(`        (sqrt_path(${rs(size)}, ${num(ev)}, ${num(vbh)}), ${s.length}, ${fnv(s)}),`);
            }
        }
    }
    for (const y of [1000, 1234.5678, 0]) {
        const s = K.phasePath(y);
        cases.push(`        (phase_path(${num(y)}), ${s.length}, ${fnv(s)}),`);
    }
    for (const name of ["\u239c", "\u2223", "\u2225", "\u239f", "\u23a2", "\u23a5", "\u23aa", "\u23d0", "\u2016", "x"]) {
        const ch = JSON.parse(`"${name}"`);
        for (const h of [0, 1234.5, 0.1 + 0.2]) {
            const s = K.innerPath(ch, h);
            cases.push(`        (inner_path(${rs(ch)}, ${num(h)}), ${s.length}, ${fnv(s)}),`);
        }
    }
    for (const label of ["lbrack", "rbrack", "vert", "doublevert", "lfloor", "rfloor", "lceil", "rceil", "lparen", "rparen"]) {
        for (const mh of [0, 123.45, -0, 1e-7]) {
            const s = K.tallDelim(label, mh);
            cases.push(`        (tall_delim(${rs(label)}, ${num(mh)}).unwrap(), ${s.length}, ${fnv(s)}),`);
        }
    }
    const VB = "    // BEGIN GENERATED SVG VECTORS";
    const VE = "    // END GENERATED SVG VECTORS";
    const va = text.indexOf(VB);
    const vb = text.indexOf(VE);
    if (va < 0 || vb < va) throw new Error("svg_geometry.rs: vector markers not found");
    text = text.slice(0, va) + `${VB}
    #[test]
    #[rustfmt::skip]
    fn parametric_paths_match_katex() {
        let cases: Vec<(String, usize, u64)> = vec![
${cases.join("\n")}
        ];
        for (i, (s, len, hash)) in cases.iter().enumerate() {
            assert_eq!((s.len(), fnv(s)), (*len, *hash), "case {i}: {s}");
        }
        assert!(tall_delim("nope", 0.0).is_none());
    }
` + text.slice(vb);
    if (text !== old) {
        fs.writeFileSync(file, text);
    }
    console.log(`spliced ${names.length} paths and ${cases.length} test vectors into src/svg_geometry.rs`);
}
