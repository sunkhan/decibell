#!/usr/bin/env python3
"""Generates src/data/font_advances.rs from KaTeX's 20 TTFs (assets/fonts/katex/, copied from
KaTeX 0.18.4's dist/fonts/).

The browser lays KaTeX's text out with the fonts' own advances (the TTFs have no kern, GPOS or
GSUB tables, so shaping is cmap -> hmtx), not with fontMetricsData's TFM widths; the layout pass
needs these. Also emits the vertical metrics Chromium's line boxes use (hhea, and OS/2 in case).

Usage: python3 gpui-client/crates/decibell-tex/tools/gen_font_tables.py [fontDir]
Requires fontTools.
"""

import os
import sys

from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(CRATE, "../../assets/fonts/katex")

# KatexFont variant -> file, in the enum's order (src/fonts.rs).
FONTS = [
    ("AmsRegular", "KaTeX_AMS-Regular.ttf"),
    ("CaligraphicBold", "KaTeX_Caligraphic-Bold.ttf"),
    ("CaligraphicRegular", "KaTeX_Caligraphic-Regular.ttf"),
    ("FrakturBold", "KaTeX_Fraktur-Bold.ttf"),
    ("FrakturRegular", "KaTeX_Fraktur-Regular.ttf"),
    ("MainBold", "KaTeX_Main-Bold.ttf"),
    ("MainBoldItalic", "KaTeX_Main-BoldItalic.ttf"),
    ("MainItalic", "KaTeX_Main-Italic.ttf"),
    ("MainRegular", "KaTeX_Main-Regular.ttf"),
    ("MathBoldItalic", "KaTeX_Math-BoldItalic.ttf"),
    ("MathItalic", "KaTeX_Math-Italic.ttf"),
    ("SansSerifBold", "KaTeX_SansSerif-Bold.ttf"),
    ("SansSerifItalic", "KaTeX_SansSerif-Italic.ttf"),
    ("SansSerifRegular", "KaTeX_SansSerif-Regular.ttf"),
    ("ScriptRegular", "KaTeX_Script-Regular.ttf"),
    ("Size1Regular", "KaTeX_Size1-Regular.ttf"),
    ("Size2Regular", "KaTeX_Size2-Regular.ttf"),
    ("Size3Regular", "KaTeX_Size3-Regular.ttf"),
    ("Size4Regular", "KaTeX_Size4-Regular.ttf"),
    ("TypewriterRegular", "KaTeX_Typewriter-Regular.ttf"),
]


def const_name(variant):
    out = ""
    for i, ch in enumerate(variant):
        if ch.isupper() and i > 0 and not variant[i - 1].isdigit():
            out += "_"
        out += ch.upper()
    return out


def main():
    out = []
    out.append(
        "// Generated by tools/gen_font_tables.py from KaTeX 0.18.4's TTFs (assets/fonts/katex/). "
        "Do not edit; regenerate.\n"
    )
    out.append(
        "//! Horizontal advances (font units) of every code point each KaTeX face maps, and the faces'\n"
        "//! vertical metrics. The TTFs have no kern/GPOS/GSUB tables, so a run's width is the sum of its\n"
        "//! characters' advances.\n\n"
        "use crate::fonts::KatexFont;\n\n"
    )
    total = 0
    tables = []
    metrics = []
    upm_all = set()
    for variant, file in FONTS:
        font = TTFont(os.path.join(FONT_DIR, file))
        upm = font["head"].unitsPerEm
        upm_all.add(upm)
        cmap = font.getBestCmap()
        hmtx = font["hmtx"]
        entries = []
        for cp in sorted(cmap):
            adv, _lsb = hmtx[cmap[cp]]
            if not (0 <= adv <= 0xFFFF):
                raise SystemExit(f"{file}: advance {adv} out of u16")
            entries.append((cp, adv))
        total += len(entries)
        tables.append((variant, entries))
        hhea = font["hhea"]
        os2 = font["OS/2"]
        metrics.append(
            (
                variant,
                (hhea.ascent, hhea.descent, hhea.lineGap),
                (os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap, os2.usWinAscent, os2.usWinDescent),
            )
        )
    if upm_all != {1000}:
        raise SystemExit(f"unitsPerEm not all 1000: {upm_all}")
    out.append(
        f"/// Every face has 1000 units per em.\npub const UNITS_PER_EM: u16 = 1000;\n\n"
        f"/// `(code point, advance)` pairs, sorted by code point ({total} entries over the 20 faces).\n"
        "pub fn advances(font: KatexFont) -> &'static [(u32, u16)] {\n    match font {\n"
    )
    for variant, _ in tables:
        out.append(f"        KatexFont::{variant} => {const_name(variant)},\n")
    out.append("    }\n}\n\n")
    out.append(
        "/// The advance of `c` in `font` (font units), or `None` if the face does not map it (the\n"
        "/// browser then falls back to another font).\n"
        "pub fn advance(font: KatexFont, c: char) -> Option<u16> {\n"
        "    let t = advances(font);\n"
        "    t.binary_search_by(|(k, _)| k.cmp(&(c as u32)))\n"
        "        .ok()\n"
        "        .map(|i| t[i].1)\n"
        "}\n\n"
    )
    out.append(
        "/// `hhea` ascent, descent (negative), lineGap, in font units.\n"
        "pub fn hhea(font: KatexFont) -> (i16, i16, i16) {\n    match font {\n"
    )
    for variant, h, _ in metrics:
        out.append(f"        KatexFont::{variant} => ({h[0]}, {h[1]}, {h[2]}),\n")
    out.append("    }\n}\n\n")
    out.append(
        "/// `OS/2` sTypoAscender, sTypoDescender, sTypoLineGap, usWinAscent, usWinDescent (font units).\n"
        "/// No face sets USE_TYPO_METRICS (fsSelection bit 7).\n"
        "pub fn os2(font: KatexFont) -> (i16, i16, i16, u16, u16) {\n    match font {\n"
    )
    for variant, _, o in metrics:
        out.append(f"        KatexFont::{variant} => ({o[0]}, {o[1]}, {o[2]}, {o[3]}, {o[4]}),\n")
    out.append("    }\n}\n")
    for variant, entries in tables:
        out.append(f"\n#[rustfmt::skip]\nstatic {const_name(variant)}: &[(u32, u16)] = &[\n")
        line = "   "
        for cp, adv in entries:
            item = f" ({cp}, {adv}),"
            if len(line) + len(item) > 100:
                out.append(line + "\n")
                line = "   "
            line += item
        if line.strip():
            out.append(line + "\n")
        out.append("];\n")
    path = os.path.join(CRATE, "src/data/font_advances.rs")
    with open(path, "w") as f:
        f.write("".join(out))
    print(f"wrote src/data/font_advances.rs: {total} advances over {len(FONTS)} faces")


if __name__ == "__main__":
    main()
