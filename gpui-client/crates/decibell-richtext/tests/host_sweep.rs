//! Every non-ASCII code point through the URL host check, against Blink's verdicts recorded by
//! tests/vectors/gen.mjs --sweep (`new URL` in Electron 33's renderer) in three positions:
//! `http://a<c>b.com`, `http://<c>a.com`, `http://a.b<c>`.
//!
//! `DECIBELL_RICHTEXT_WRITE_URL_TABLES=1 cargo test --test host_sweep` rewrites
//! src/url_tables.rs: the code points Blink refuses everywhere that the `idna` crate's newer
//! Unicode data accepts.

use decibell_richtext::links::is_linkable;

fn verdict(c: char) -> [u8; 3] {
    let v = |s: String| if is_linkable(&s) { b'1' } else { b'0' };
    [v(format!("http://a{c}b.com")), v(format!("http://{c}a.com")), v(format!("http://a.b{c}"))]
}

#[test]
fn host_sweep() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/vectors/host-sweep.json");
    let ranges: Vec<(u32, u32, String)> = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    let mut diffs: Vec<(u32, String, String)> = Vec::new();
    let mut reject: Vec<(u32, u32)> = Vec::new();
    let mut checked = 0usize;
    for (a, b, want) in &ranges {
        for cp in *a..=*b {
            let Some(c) = char::from_u32(cp) else { continue };
            checked += 1;
            let got = verdict(c);
            if got != want.as_bytes() {
                let got = String::from_utf8(got.to_vec()).unwrap();
                if want == "000" {
                    match reject.last_mut() {
                        Some(r) if r.1 + 1 == cp => r.1 = cp,
                        _ => reject.push((cp, cp)),
                    }
                }
                diffs.push((cp, want.clone(), got));
            }
        }
    }
    if std::env::var_os("DECIBELL_RICHTEXT_WRITE_URL_TABLES").is_some() {
        // Merge with the current table (its entries already pass) and write it back.
        let cur = std::fs::read_to_string(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/url_tables.rs")).unwrap();
        let mut all: Vec<(u32, u32)> = reject.clone();
        for cap in cur.split("(0x").skip(1) {
            let a = u32::from_str_radix(&cap[..cap.find(',').unwrap()], 16).unwrap();
            let rest = &cap[cap.find("0x").unwrap() + 2..];
            let b = u32::from_str_radix(&rest[..rest.find(')').unwrap()], 16).unwrap();
            all.push((a, b));
        }
        all.sort();
        let mut merged: Vec<(u32, u32)> = Vec::new();
        for (a, b) in all {
            match merged.last_mut() {
                Some(m) if a <= m.1 + 1 => m.1 = m.1.max(b),
                _ => merged.push((a, b)),
            }
        }
        let mut s = String::from(
            "// @generated by tests/host_sweep.rs (DECIBELL_RICHTEXT_WRITE_URL_TABLES=1) — do not edit.\n\
             /// Code points Electron 33's Blink refuses in a URL host although the `idna` crate's UTS #46\n\
             /// data (Unicode 16) accepts them: assigned after Unicode 15.1, or with a changed status.\n",
        );
        s.push_str(&format!("pub(crate) static CHROMIUM_IDNA_REJECT: [(u32, u32); {}] = [\n", merged.len()));
        for c in merged.chunks(6) {
            s.push_str("    ");
            s.push_str(&c.iter().map(|(a, b)| format!("(0x{a:X}, 0x{b:X})")).collect::<Vec<_>>().join(", "));
            s.push_str(",\n");
        }
        s.push_str("];\n");
        std::fs::write(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/url_tables.rs"), s).unwrap();
        eprintln!("wrote src/url_tables.rs");
    }
    for (cp, want, got) in diffs.iter().filter(|d| d.1 != "000").take(40) {
        eprintln!("U+{cp:04X}: blink {want}, rust {got}");
    }
    println!("host sweep: {checked} code points × 3 positions compared, {} differ ({} fixable by the reject table)", diffs.len(), reject.len());
    assert!(diffs.is_empty());
}
