//! Embeds every SVG under gpui-client/assets/icons and names it:
//! - `$OUT_DIR/icons.rs`: a table of (asset path, bytes) sorted by path, which `assets.rs` serves
//!   to GPUI;
//! - `$OUT_DIR/icon_names.rs`: the `IconName` enum, one variant per file, so a missing icon is a
//!   compile error. `icons/close.svg` → `IconName::Close`, `icons/stage/mic-off.svg` →
//!   `IconName::StageMicOff`, `icons/lucide/user-plus.svg` → `IconName::LucideUserPlus`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let icons = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/icons");
    let icons = icons.canonicalize().expect("gpui-client/assets/icons");
    let mut files = Vec::new();
    collect(&icons, &mut files);
    // Sorted by the asset name as a string (what `Assets` binary-searches), not by path
    // components: `settings-tab/…` sorts before `settings/…` as a string.
    let mut files: Vec<(String, PathBuf)> = files
        .into_iter()
        .map(|file| {
            let name = file
                .strip_prefix(&icons)
                .unwrap()
                .to_str()
                .unwrap()
                .replace('\\', "/");
            (name, file)
        })
        .collect();
    files.sort();

    let mut table = String::from("pub static ICONS: &[(&str, &[u8])] = &[\n");
    let mut names: Vec<(String, String)> = Vec::new();
    for (name, file) in &files {
        writeln!(
            table,
            "    (\"icons/{name}\", include_bytes!({:?})),",
            file.to_str().unwrap()
        )
        .unwrap();
        names.push((variant(name), format!("icons/{name}")));
    }
    table.push_str("];\n");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    std::fs::write(out.join("icons.rs"), table).unwrap();

    let mut seen = std::collections::HashSet::new();
    for (variant, path) in &names {
        assert!(seen.insert(variant), "{path}: the icon name {variant} is taken twice");
    }
    let mut enum_src = String::from(
        "/// Every bundled icon (`gpui-client/assets/icons`), named after its file: draw one with\n\
         /// [`Icon::new`](crate::Icon::new). Generated by `decibell-ui`'s build script.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum IconName {\n",
    );
    for (variant, path) in &names {
        writeln!(enum_src, "    /// `{path}`\n    {variant},").unwrap();
    }
    enum_src.push_str("}\n\nimpl IconName {\n    /// Every icon, in path order.\n    pub const ALL: &[IconName] = &[\n");
    for (variant, _) in &names {
        writeln!(enum_src, "        IconName::{variant},").unwrap();
    }
    enum_src.push_str("    ];\n\n    /// The asset path GPUI loads it by.\n    pub const fn path(self) -> &'static str {\n        match self {\n");
    for (variant, path) in &names {
        writeln!(enum_src, "            IconName::{variant} => {path:?},").unwrap();
    }
    enum_src.push_str("        }\n    }\n}\n");
    std::fs::write(out.join("icon_names.rs"), enum_src).unwrap();
}

/// `stage/mic-off.svg` → `StageMicOff`.
fn variant(relative: &str) -> String {
    let stem = relative.strip_suffix(".svg").unwrap();
    let mut out = String::new();
    for word in stem.split(['/', '-', '_', '.']) {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.extend(chars);
        }
    }
    assert!(
        out.chars().next().is_some_and(|c| c.is_ascii_alphabetic()),
        "{relative}: an icon file name must start with a letter"
    );
    out
}

fn collect(dir: &Path, files: &mut Vec<PathBuf>) {
    // A new or removed file changes the directory's mtime.
    println!("cargo:rerun-if-changed={}", dir.display());
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            collect(&path, files);
        } else if path.extension().is_some_and(|extension| extension == "svg") {
            println!("cargo:rerun-if-changed={}", path.display());
            files.push(path);
        }
    }
}
